// Turns a validated plan into a Playwright test file.
// Fresh mock data is generated per run (timestamp email) so reruns never
// collide with earlier accounts - no real people's data, ever.
export function generateTest({ plan, inspection }) {
  const s = inspection.selectors;
  const assertions = new Set(plan.assertions);
  const lines = [];
  lines.push(`// Generated by Plain-English Playwright Test Writer`);
  lines.push(`// Goal: ${plan.goal}`);
  lines.push(`// Source inspected: ${inspection.source.url} at ${inspection.source.retrievedAt}`);
  lines.push(`import { test, expect } from '@playwright/test';`);
  lines.push(`import { startLiveStream } from '../server/liveStream.js';`);
  lines.push(``);
  lines.push(`test('${escapeSq(plan.goal)}', async ({ page, request }, testInfo) => {`);
  lines.push(`  // Stream the real browser screen to the page while this test acts.`);
  lines.push(`  const stopLive = await startLiveStream(page);`);
  lines.push(`  try {`);
  lines.push(`  const stamp = Date.now();`);
  lines.push(`  const user = {`);
  lines.push(`    name: ${JSON.stringify(plan.fields?.name || 'Test User')},`);
  lines.push(`    // Date.now() alone can collide across simultaneous runs; add a random suffix.
    email: \`testuser\${stamp}-\${Math.random().toString(36).slice(2, 8)}@example.com\`,`);
  lines.push(`    password: ${JSON.stringify(plan.fields?.password || 'Passw0rd!123')},`);
  lines.push(`  };`);
  lines.push(``);
  lines.push(`  // DEMO_TARGET_VERSION lets us rerun this exact test after the app changes (TC2).`);
  lines.push(`  const targetVersion = process.env.DEMO_TARGET_VERSION || '${plan.version}';`);
  lines.push(`  await page.goto(\`${plan.baseUrl}/demo/\${targetVersion}/signup\`);`);
  lines.push(`  await page.getByTestId('${s.name}').fill(user.name);`);
  lines.push(`  await page.getByTestId('${s.email}').fill(user.email);`);
  lines.push(`  await page.getByTestId('${s.password}').fill(user.password);`);
  lines.push(`  await page.getByTestId('${s.submit}').click();`);
  lines.push(``);
  if (assertions.has('url-contains-dashboard')) {
    lines.push(`  await expect(page).toHaveURL(/\\/demo\\/dashboard/);`);
  }
  if (assertions.has('welcome-visible')) {
    lines.push(`  await expect(page.getByTestId('welcome-heading')).toBeVisible();`);
    lines.push(`  await expect(page.getByTestId('welcome-heading')).toContainText(user.name);`);
  }
  if (assertions.has('user-record-exists')) {
    lines.push(`  const res = await request.get('${plan.baseUrl}/demo/api/users');`);
    lines.push(`  expect(res.ok()).toBeTruthy();`);
    lines.push(`  const data = await res.json();`);
    lines.push(`  const mine = data.users.filter((u) => u.email === user.email);`);
    lines.push(`  expect(mine.length).toBeGreaterThanOrEqual(1);`);
    if (assertions.has('no-duplicate-account')) {
      lines.push(`  // TC4: a rerun with fresh data must never create a duplicate account.`);
      lines.push(`  expect(mine.length).toBe(1);`);
    }
  }
  lines.push(`  } finally {`);
  lines.push(`    // Freeze the live feed at the final state, then capture evidence.`);
  lines.push(`    if (stopLive) await stopLive();`);
  lines.push(`    // Real run evidence: capture what the runner's browser actually showed`);
  lines.push(`    // at the end of this test (pass or fail) and attach it to the report.`);
  lines.push(`    const shot = await page.screenshot().catch(() => null);`);
  lines.push(`    if (shot) await testInfo.attach('final-page-state', { body: shot, contentType: 'image/png' });`);
  lines.push(`  }`);
  lines.push(`});`);
  lines.push(``);
  return lines.join('\n');
}

export function escapeSq(text) {
  // The goal lands inside a single-quoted string in generated code: quotes,
  // backslashes and raw newlines would otherwise break the file's syntax.
  return String(text)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, ' ');
}
