// Turns a validated plan into a Playwright test file.
// Fresh mock data is generated per run (timestamp email) so reruns never
// collide with earlier accounts - no real people's data, ever.

// The exact ordered list of actions the generated test will take, in plain
// language, with the locator each action uses. The server shows this list
// before the run (approval gate) and the generated test reports progress
// against these same indices, so the UI can never invent steps the test
// does not perform.
export function signupSteps({ plan, inspection }) {
  const s = inspection.selectors;
  const assertions = new Set(plan.assertions);
  const submitLabel = inspection.submit?.label || 'the submit button';
  const steps = [
    { label: `Open the ${plan.version === 'v2' ? 'v2' : 'v1'} sign-up page`, locator: `page.goto('/demo/${plan.version}/signup')` },
    { label: 'Type the full name', locator: `getByTestId('${s.name}')` },
    { label: 'Type a fresh email', locator: `getByTestId('${s.email}')` },
    { label: 'Type the password', locator: `getByTestId('${s.password}')` },
    { label: `Click "${submitLabel}"`, locator: `getByTestId('${s.submit}')` },
  ];
  if (assertions.has('url-contains-dashboard')) {
    steps.push({ label: 'Check the address bar shows the dashboard', locator: `toHaveURL(/\\/demo\\/dashboard/)` });
  }
  if (assertions.has('welcome-visible')) {
    steps.push({ label: 'Check the dashboard welcomes the new user', locator: `getByTestId('welcome-heading')` });
  }
  if (assertions.has('user-record-exists')) {
    steps.push({ label: 'Check the account was saved', locator: 'GET /demo/api/users' });
  }
  if (assertions.has('no-duplicate-account')) {
    steps.push({ label: 'Check a rerun never duplicates the account', locator: 'expect(mine.length).toBe(1)' });
  }
  return steps;
}

export function generateTest({ plan, inspection }) {
  const s = inspection.selectors;
  const assertions = new Set(plan.assertions);
  const steps = signupSteps({ plan, inspection });
  const idx = (label) => steps.findIndex((st) => st.label === label);
  const stepIdx = {
    goto: 0, name: 1, email: 2, password: 3, submit: 4,
    url: idx('Check the address bar shows the dashboard'),
    welcome: idx('Check the dashboard welcomes the new user'),
    record: idx('Check the account was saved'),
    dup: idx('Check a rerun never duplicates the account'),
  };
  const act = (i) => ({
    start: `  await act(${i}, 'running');`,
    end: `  await act(${i}, 'done');`,
  });
  const lines = [];
  lines.push(`// Generated by Plain-English Playwright Test Writer`);
  lines.push(`// Goal: ${plan.goal}`);
  lines.push(`// Source inspected: ${inspection.source.url} at ${inspection.source.retrievedAt}`);
  lines.push(`import { test, expect } from '@playwright/test';`);
  lines.push(`import { startLiveStream, reportAction } from '../server/liveStream.js';`);
  lines.push(``);
  lines.push(`test('${escapeSq(plan.goal)}', async ({ page, request }, testInfo) => {`);
  lines.push(`  // Stream the real browser screen to the page while this test acts.`);
  lines.push(`  const stopLive = await startLiveStream(page);`);
  lines.push(`  // Report each real action to the workspace as it happens (no-op off-server).`);
  lines.push(`  let currentStep = -1;`);
  lines.push(`  const act = async (i, status) => { if (status === 'running') currentStep = i; await reportAction(i, status); };`);
  lines.push(`  try {`);
  lines.push(`  const stamp = Date.now();`);
  lines.push(`  const user = {`);
  lines.push(`    name: ${JSON.stringify(plan.fields?.name || 'Test User')},`);
  lines.push(`    // Date.now() alone can collide across simultaneous runs; add a random suffix.
    email: \`testuser\${stamp}-\${Math.random().toString(36).slice(2, 8)}@example.com\`,`);
  lines.push(`    password: ${JSON.stringify(plan.fields?.password || 'Passw0rd!123')},`);
  lines.push(`  };`);
  lines.push(``);
  lines.push(`  // DEMO_TARGET_VERSION lets us rerun this exact test after the app changes (TC2).`);
  lines.push(`  const targetVersion = process.env.DEMO_TARGET_VERSION || '${plan.version}';`);
  lines.push(act(stepIdx.goto).start);
  lines.push(`  await page.goto(\`${plan.baseUrl}/demo/\${targetVersion}/signup\`);`);
  lines.push(act(stepIdx.goto).end);
  lines.push(act(stepIdx.name).start);
  lines.push(`  await page.getByTestId('${s.name}').fill(user.name);`);
  lines.push(act(stepIdx.name).end);
  lines.push(act(stepIdx.email).start);
  lines.push(`  await page.getByTestId('${s.email}').fill(user.email);`);
  lines.push(act(stepIdx.email).end);
  lines.push(act(stepIdx.password).start);
  lines.push(`  await page.getByTestId('${s.password}').fill(user.password);`);
  lines.push(act(stepIdx.password).end);
  lines.push(act(stepIdx.submit).start);
  lines.push(`  await page.getByTestId('${s.submit}').click();`);
  lines.push(act(stepIdx.submit).end);
  lines.push(``);
  if (stepIdx.url >= 0) {
    lines.push(act(stepIdx.url).start);
    lines.push(`  await expect(page).toHaveURL(/\\/demo\\/dashboard/);`);
    lines.push(act(stepIdx.url).end);
  }
  if (stepIdx.welcome >= 0) {
    lines.push(act(stepIdx.welcome).start);
    lines.push(`  await expect(page.getByTestId('welcome-heading')).toBeVisible();`);
    lines.push(`  await expect(page.getByTestId('welcome-heading')).toContainText(user.name);`);
    lines.push(act(stepIdx.welcome).end);
  }
  if (stepIdx.record >= 0) {
    lines.push(act(stepIdx.record).start);
    lines.push(`  const res = await request.get('${plan.baseUrl}/demo/api/users');`);
    lines.push(`  expect(res.ok()).toBeTruthy();`);
    lines.push(`  const data = await res.json();`);
    lines.push(`  const mine = data.users.filter((u) => u.email === user.email);`);
    lines.push(`  expect(mine.length).toBeGreaterThanOrEqual(1);`);
    lines.push(act(stepIdx.record).end);
    if (stepIdx.dup >= 0) {
      lines.push(act(stepIdx.dup).start);
      lines.push(`  // TC4: a rerun with fresh data must never create a duplicate account.`);
      lines.push(`  expect(mine.length).toBe(1);`);
      lines.push(act(stepIdx.dup).end);
    }
  }
  lines.push(`  } catch (err) {`);
  lines.push(`    // Mark the step that was acting when the failure happened.`);
  lines.push(`    if (currentStep >= 0) await reportAction(currentStep, 'failed');`);
  lines.push(`    throw err;`);
  lines.push(`  } finally {`);
  lines.push(`    // Freeze the live feed at the final state, then capture evidence.`);
  lines.push(`    if (stopLive) await stopLive();`);
  lines.push(`    // Real run evidence: capture what the runner's browser actually showed`);
  lines.push(`    // at the end of this test (pass or fail) and attach it to the report.`);
  lines.push(`    const shot = await page.screenshot().catch(() => null);`);
  lines.push(`    if (shot) await testInfo.attach('final-page-state', { body: shot, contentType: 'image/png' });`);
  lines.push(`  }`);
  lines.push(`});`);
  lines.push(``);
  return lines.join('\n');
}

export function escapeSq(text) {
  // The goal lands inside a single-quoted string in generated code: quotes,
  // backslashes and raw newlines would otherwise break the file's syntax.
  return String(text)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\r?\n/g, ' ');
}
